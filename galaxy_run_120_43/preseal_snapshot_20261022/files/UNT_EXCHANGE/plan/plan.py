#!/usr/bin/env python3
"""UNT shared PLAN. plan.tsv is the source of truth; PLAN.md is generated.

  python3 plan.py                                   render PLAN.md and print it
  python3 plan.py set P-3 DONE "evidence path" --by Codex
  python3 plan.py add 2 P-16 "task" "done when ..." Codex --by Claude
  python3 plan.py owner P-13 Codex2 --by Claude
Rows append; IDs never renumber; a wrong task becomes DROPPED with its reason.
"""
import csv, sys, datetime, pathlib
HERE = pathlib.Path(__file__).resolve().parent
TSV, LOG, OUT = HERE/"plan.tsv", HERE/"plan_log.tsv", HERE.parent/"PLAN.md"
FIELDS = ["id", "phase", "owner", "status", "task", "done_when", "evidence"]
STATUS = ["TODO", "ACTIVE", "DONE", "BLOCKED", "HOLD", "DROPPED"]
PHASES = {"1": "Foundations: one model, honest tests",
          "2": "Does the model make gravity?",
          "3": "Prediction: 120/43",
          "P": "Parallel and maintenance"}
GOAL = ("Adopted 2026-10-13: one shared UNT construction explaining dark-matter and dark-energy phenomena "
        "through record behavior, with the native geometry/motion/expansion chain established before 120/43. "
        "Current work: connected native propagation, common response and growth/measure feasibility; initial source and finite-operation milestones are complete at scoped levels. Legacy held rows are not reauthorized. "
        "Authority: UNT_PROGRAM_CONTROL/CURRENT_INSTRUCTIONS.md.")

def clean(s):
    if "\t" in s or "\n" in s: sys.exit("fields may not contain tabs or newlines")
    return s.strip()

def load():
    with open(TSV, newline="") as f:
        rows = list(csv.DictReader(f, delimiter="\t"))
    for r in rows:
        if r["status"] not in STATUS: sys.exit(f"{r['id']}: status {r['status']} not in {STATUS}")
        if r["phase"] not in PHASES: sys.exit(f"{r['id']}: unknown phase {r['phase']}")
    return rows

def save(rows):
    with open(TSV, "w", newline="") as f:
        w = csv.DictWriter(f, FIELDS, delimiter="\t", lineterminator="\n"); w.writeheader(); w.writerows(rows)

def log(who, ident, change):
    new = not LOG.exists()
    with open(LOG, "a", newline="") as f:
        if new: f.write("utc\tby\tid\tchange\n")
        f.write(f"{datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%MZ')}\t{who}\t{ident}\t{change}\n")

ABBR = [("/Users/bgm/Research/Universal Network Theory/UNT_DARK_SECTOR_CONTINUOUS_2026-09-27_V001/joint_parent_continuation/ROOT_UNT_LOCAL_RESIDENCY_MANIFEST_V002/exploratory_physics/PHASE12_PARALLEL_SCREEN_V001/H_record_front_provisional_V001/", "H/"),
        ("/Users/bgm/Research/Universal Network Theory/UNT_DARK_SECTOR_CONTINUOUS_2026-09-27_V001/joint_parent_continuation/", "J/"),
        ("/Users/bgm/Research/Universal Network Theory/", "R/")]

def short(s):
    for full, ab in ABBR: s = s.replace(full, ab)
    return s

def render(rows):
    L = ["# UNT PLAN", "", "*Generated by `plan/plan.py` from `plan/plan.tsv`. Do not edit by hand.*", "",
         f"**Goal:** {GOAL}", ""]
    counts = {s: sum(r["status"] == s for r in rows) for s in STATUS}
    L += ["**Status:** " + " · ".join(f"{s} {counts[s]}" for s in STATUS if counts[s]), ""]
    active = [r["id"] for r in rows if r["status"] == "ACTIVE"]
    nxt = next((r["id"] for p in PHASES for r in rows if r["phase"] == p and r["status"] == "TODO"), "none")
    L += [f"**Active:** {', '.join(active) or 'none'}  ·  **Next TODO:** {nxt}", ""]
    for p, title in PHASES.items():
        sel = [r for r in rows if r["phase"] == p]
        if not sel: continue
        L += [f"## Phase {p}: {title}", "", "| ID | Status | Owner | Task | Done when | Evidence |", "|---|---|---|---|---|---|"]
        for r in sel:
            L.append(f"| {r['id']} | **{r['status']}** | {r['owner']} | {r['task']} | {r['done_when']} | {short(r['evidence']) or '—'} |")
        L.append("")
    L += ["Paths: R/ = `/Users/bgm/Research/Universal Network Theory/`; J/ = `R/UNT_DARK_SECTOR_CONTINUOUS_2026-09-27_V001/joint_parent_continuation/`; "
          "H/ = `J/ROOT_UNT_LOCAL_RESIDENCY_MANIFEST_V002/exploratory_physics/PHASE12_PARALLEL_SCREEN_V001/H_record_front_provisional_V001/`.", ""]
    L += ["Rules: rows append and IDs never renumber; DONE needs evidence that meets *Done when*; "
          "a wrong task becomes DROPPED with its reason, and a better one is appended. Changes are logged in `plan/plan_log.tsv`."]
    return "\n".join(L) + "\n"

def main(a):
    rows = load()
    by = "unknown"
    if "--by" in a:
        i = a.index("--by"); by = a[i+1]; a = a[:i] + a[i+2:]
    if a and a[0] == "set":
        ident, st = a[1], a[2]; ev = clean(a[3]) if len(a) > 3 else ""
        if st not in STATUS: sys.exit(f"status must be one of {STATUS}")
        r = next((r for r in rows if r["id"] == ident), None) or sys.exit(f"no task {ident}")
        if st == "DONE" and not ev: sys.exit("DONE requires evidence")
        old = r["status"]; r["status"] = st
        if ev: r["evidence"] = ev
        save(rows); log(by, ident, f"{old}->{st} {ev}".strip())
    elif a and a[0] == "owner":
        ident, new = a[1], clean(a[2])
        r = next((r for r in rows if r["id"] == ident), None) or sys.exit(f"no task {ident}")
        old = r["owner"]; r["owner"] = new
        save(rows); log(by, ident, f"owner {old}->{new}")
    elif a and a[0] == "add":
        phase, ident, task, done, owner = a[1:6]
        if phase not in PHASES: sys.exit("unknown phase")
        if any(r["id"] == ident for r in rows): sys.exit("ID exists; IDs never reuse")
        rows.append(dict(id=ident, phase=phase, owner=clean(owner), status="TODO", task=clean(task), done_when=clean(done), evidence=""))
        save(rows); log(by, ident, f"added: {task}")
    elif a:
        sys.exit(__doc__)
    text = render(load()); OUT.write_text(text); print(text, end="")

if __name__ == "__main__":
    main(sys.argv[1:])
