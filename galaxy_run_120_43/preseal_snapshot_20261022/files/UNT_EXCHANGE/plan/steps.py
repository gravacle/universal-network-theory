"""UNT Galaxy Run: the locked N-step plan.

steps.tsv lists the steps. They are LOCKED: never added, removed or renumbered.
step_map.tsv attaches PLAN tasks (plan.tsv rows) to steps; new work is attached, never a new step.
A step's status comes from its tasks: DONE when every task is DONE or DROPPED (and at least one is DONE);
ACTIVE when any task is ACTIVE or DONE; otherwise TODO.

  python3 steps.py                    print the step view (and write STEPS.md)
  python3 steps.py attach P-119 S4    attach a PLAN task to a step (appends to step_map.tsv)
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def rows(name):
    with open(os.path.join(HERE, name), newline='') as f:
        return list(csv.DictReader(f, delimiter='\t'))


def main(argv):
    steps = rows('steps.tsv')
    tasks = {r['id']: r for r in rows('plan.tsv')}
    if argv[:1] == ['attach']:
        pid, sid = argv[1], argv[2]
        if pid not in tasks:
            sys.exit('no PLAN task ' + pid)
        if sid not in {s['step'] for s in steps}:
            sys.exit('no step ' + sid + ' (steps are locked; attach to an existing one)')
        if any(m['id'] == pid for m in rows('step_map.tsv')):
            sys.exit(pid + ' is already attached')
        with open(os.path.join(HERE, 'step_map.tsv'), 'a') as f:
            f.write(pid + '\t' + sid + '\n')
    smap = {}
    for m in rows('step_map.tsv'):
        smap.setdefault(m['step'], []).append(m['id'])
    out, current = [], None
    out.append('| Step | Status | Target (CDT/CST) | Open tasks | What finishes it |')
    out.append('|---|---|---|---|---|')
    for s in steps:
        ids = smap.get(s['step'], [])
        st = [tasks[i]['status'] for i in ids if i in tasks]
        done = [x for x in st if x in ('DONE', 'DROPPED')]
        if st and len(done) == len(st) and 'DONE' in st:
            status = 'DONE'
        elif any(x in ('ACTIVE', 'DONE') for x in st):
            status = 'ACTIVE'
        else:
            status = 'TODO'
        if status != 'DONE' and current is None:
            current = s['step']
        open_ids = [i for i in ids if i in tasks and tasks[i]['status'] not in ('DONE', 'DROPPED')]
        out.append('| %s. %s | %s | %s | %s | %s |' % (s['step'], s['title'], status, s['target'],
                                                       ', '.join(open_ids) or '-', s['done_when']))
    out.append('')
    out.append('Earliest unfinished step: %s. Steps are locked; new tasks are attached to a step.' % current)
    text = '\n'.join(out)
    with open(os.path.join(HERE, 'STEPS.md'), 'w') as f:
        f.write('# UNT Galaxy Run: locked step plan (generated by steps.py; do not edit)\n\n' + text + '\n')
    print(text)


if __name__ == '__main__':
    main(sys.argv[1:])
