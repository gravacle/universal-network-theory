    rc, txt = quiet(St.main, ['wave', '--work-dir', work, '--next-calls', '1000000'])
    check('S02.storage_wave_check_reports_HALTED_DISK_exit_5_for_a_wave_that_cannot_fit', 'MUST_FAIL', rc == 5, rc)
    rc, txt = quiet(St.main, ['move', '--candidate', str(Path(w['dir']) / 'CERTS'), '--work-dir', work, '--pins-from',
                              w['T3']['path']])
    check('S03.storage_move_check_refuses_a_directory_holding_pinned_files_(the_registry)', 'MUST_FAIL', rc == 3,
          str((last_json(txt) or {}).get('reasons'))[:120])
    rc, txt = quiet(St.main, ['move', '--candidate', str(Path(w['dir'])), '--work-dir', work, '--pins-from', w['T3']['path']])
    check('S04.storage_move_check_refuses_a_directory_that_holds_the_campaign_work_dir', 'MUST_FAIL', rc == 3,
          str((last_json(txt) or {}).get('reasons'))[-120:])
    free = Path(w['dir']) / 'FREE_TO_MOVE'
    free.mkdir()
    put_x(free / 'unpinned.txt', None, raw=b'x\n')
    rc, txt = quiet(St.main, ['move', '--candidate', str(free), '--work-dir', work, '--pins-from', w['T3']['path'], '--follow'])
    check('S05.storage_move_check_admits_an_unpinned_directory_outside_the_work_dir', 'MUST_PASS', rc == 0,
          (last_json(txt) or {}).get('n_pins'))


