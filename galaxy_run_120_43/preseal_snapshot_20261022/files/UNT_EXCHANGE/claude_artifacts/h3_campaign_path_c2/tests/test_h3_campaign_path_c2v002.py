def make_post_state_bundle(w, call, producer, dirname):
    """A post-state bundle shaped as the handoff writes it, built WITHOUT the handoff, whose LO proofs name `producer`
    (c2v001's make_wrong_producer_bundle with the producer and folder as parameters)."""
    W, S = w['W'], load(w['syn_module']['path'], '_h3_t_syn_%s' % dirname)
    spec = json.loads((call / 'spec.json').read_text())
    res = json.loads((call / 'out' / 'result.json').read_text())
    reg = json.loads(Path(w['registry']['path']).read_bytes())
    rec = reg['points'][W.M.digest(W.point_identity(spec))]
    inv = S.consumed_states(spec=spec, result=res, call_dir=str(call))
    d = Path(w['dir']) / dirname
    d.mkdir()
    lo = S.adapt_call_lo(spec, call_dir=str(call), result=res, inventory=inv, bundle_ref=rec['bundle'], state_inputs={},
                         root_ruling_refs={'SYN_LO_PRODUCER': producer}, approved_producer_sha256=[],
                         trusted_source_producers=[], trusted_row_policy_review_sha256=[], out_root=str(d))
    pre = json.loads(Path(rec['bundle']['path']).read_bytes())
    b = dict(pre, parent_prelaunch_bundle=rec['bundle'], states=[{'state': x['state'], 'LO': x['record']} for x in lo['states']])
    return put_x(d / ('POST_STATE_BUNDLE_%s.json' % dirname), b)


def in_process_reingest(w, cfg, wave, call_index, bundle, record, entry=None):
    """An entry's reingest() in this process on world w's patched wrapper, with dispatch's refusal handling.
    entry=ENTRY_V1 calls the c2v001 function (no record argument): the B2 contrast."""
    E = load(entry or w['entry'], '_h3_t_entry_ip_%d' % time.monotonic_ns())
    W = w['W']
    try:
        if entry == ENTRY_V1:
            return E.reingest(W, cfg, wave, call_index, bundle)
        return E.reingest(W, cfg, wave, call_index, bundle, record)
    except (W.Error, W.CertificateRefusal, OSError, ValueError, KeyError, TypeError) as exc:
        return {'status': 'REFUSED', 'reasons': ['%s: %s' % (type(exc).__name__, exc)]}


def reingest_cmd(w, cfg, wave, call_index, bundle, record, tag):
    """The entry CLI `reingest` in its own process; bundle / record are pins or (path, sha) tuples."""
